def seed_rules():
    Base.metadata.create_all(bind=engine)
    session = SessionLocal()
    try:
        updated = 0
        created = 0
        for rule_dict in STANDARD_RULES:
            existing = (
                session.query(MaintenanceRule)
                .filter(
                    MaintenanceRule.vehicle_model == rule_dict["vehicle_model"],
                    MaintenanceRule.component_name == rule_dict["component_name"],
                    MaintenanceRule.service_task == rule_dict["service_task"],
                )
                .first()
            )
            if existing:
                if existing.inspection_required != 1 or existing.suggested_km_interval != rule_dict["suggested_km_interval"]:
                    existing.inspection_required = 1
                    existing.suggested_km_interval = rule_dict["suggested_km_interval"]
                    updated += 1
            else:
                rule = MaintenanceRule(**rule_dict)
                session.add(rule)
                created += 1

        session.commit()
        if created > 0 or updated > 0:
            print(f"Maintenance rules seed complete: {created} created, {updated} updated.")
    finally:
        session.close()


if __name__ == "__main__":
    seed_rules()
